/**
 * Équipes de recherche du laboratoire identifiées par leur acronyme officiel.
 */
public enum EquipeLaboratoire {

    /** Équipe : Intelligence et Systèmes de Données pour l'Ingénierie Avancée et la Communication. */
    ISDIAC,

    /** Équipe : Systèmes Intelligents et Multimédia Adaptatifs. */
    SIMA,

    /** Équipe : Intelligence Logicielle et Ingénierie des Applications et Systèmes. */
    ILIAS,

    /** Équipe : Systèmes Distribués, Technologies de l'Information et de la Communication. */
    SDTIC,

    /** Équipe : Direction du laboratoire. */
    DIRECTION,

    /** Aucune équipe assignée (valeur par défaut). */
    AUCUNE
}
